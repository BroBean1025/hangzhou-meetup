// Pack only the public map layers and pure client helpers needed by WeChat.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { wgsToGcj, gcjToWgs } from '../core/lib/metro-service.mjs';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const dir = new URL('wechat/miniprogram/generated/', root);
await mkdir(dir, { recursive: true });
const save = (name, code) => writeFile(new URL(name + '.js', dir), '// Generated by tools/build-wechat.mjs\n' + code.replaceAll('\r\n','\n').trimEnd() + '\n');
const map = JSON.parse(await read('core/data/map.json'));
const { features } = JSON.parse(await read('core/data/geography.json'));
const points = map.points.map(({id,name,lon,lat,aliases,is_interchange,lines}) => ({id,name,lon,lat,aliases,is_interchange,lines}));
const campuses = map.campuses.map(({id,name,short_name,school_id,school_name,campus_name,lon,lat,origin_key,gate_options,default_enabled,logo,color,times}) => ({
  id,name,short_name,school_id,school_name,campus_name,lon,lat,origin_key,default_enabled,color,
  icon:'/icons/'+logo.split(':')[1], gates:gate_options.map(({key,label,lon,lat})=>({key,label,lon,lat})),
  hubs: map.hubs.map(h => {
    const rows=(h.member_ids||[h.id]).map(s=>times[s]?.seconds).filter(Number.isFinite);
    return rows.length?Math.min(...rows):null;
  })
}));
const boundaries = {};
for (const {properties,geometry} of features.filter(f=>f.properties.kind==='campus')) {
  const polys=geometry.type==='Polygon'?[geometry.coordinates]:geometry.coordinates;
  if(polys.some(p=>p.length!==1))throw Error('Campus polygon has holes: '+properties.campus_id);
  boundaries[properties.campus_id]=polys.map(p=>p[0]);
}
const data={points,campuses,boundaries,lines:map.lines,station_groups:map.station_groups,
  hubs:map.hubs.map(({id,name,kind,member_ids})=>({id,name,kind,member_ids})),
  segments:map.segments.map(({from,to,line,coordinates})=>({from,to,line,coordinates})),synced_at:map.synced_at,regional_data_at:map.regional_data_at};
await save('network','module.exports = '+JSON.stringify(data)+';');
for(const [file,func] of [['confluence','rankMeetingCandidates'],['rail-display','createRailDisplay'],['station-catalog','createStationCatalog']]) {
  const code=await read('core/src/'+file+'.js');
  await save(file,code+'\nmodule.exports = '+func+';');
}
const time=await read('core/src/trip-time.js');
if(!time.includes('})(globalThis);'))throw Error('Check shared planner export');
await save('trip-time',time.replace('})(globalThis);','})(module.exports);'));
await save('coordinates',[wgsToGcj,gcjToWgs].map(fn=>fn.toString()).join('\n')+'\nmodule.exports = {wgsToGcj,gcjToWgs};');
console.log('WeChat map:',points.length,'stations,',data.segments.length,'track segments,',campuses.length,'campuses.');
